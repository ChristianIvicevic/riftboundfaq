import { describe, expect, test } from 'vitest'
import { prepareCoreRulesArtifacts } from './core-rules/generate'
import type { ExtractedCoreRulesFamily, ExtractedTournamentRulesFamily } from './rules-document-family'
import { prepareTournamentRulesArtifacts } from './tournament-rules/generate'

describe('rules document artifact preparation', () => {
	test('serializes Core Rules extraction without source knowledge', () => {
		const registeredVersion = { version: '1.0', name: 'Launch' }
		const version: ExtractedCoreRulesFamily['versions'][number] = {
			registeredVersion,
			lastUpdated: '2026-01-01',
			document: { schemaVersion: 3, version: '1.0', sections: [] },
			transcript: 'Core transcript\n',
			diagnostics: [],
		}

		const prepared = prepareCoreRulesArtifacts({ versions: [version], currentVersion: version })

		expect(prepared).toStrictEqual({
			artifacts: new Map([
				[
					'v1-0.ts',
					`// Generated by pnpm rules:generate. Do not edit.

import type { CoreRulesDocument } from '@/lib/rules/core-rules-document'

// oxfmt-ignore
export const PDF_CORE_RULES_1_0: CoreRulesDocument = {
  "schemaVersion": 3,
  "version": "1.0",
  "sections": []
}
`,
				],
				[
					'index.ts',
					`// Generated by pnpm rules:generate. Do not edit.

import { PDF_CORE_RULES_1_0 } from '@/generated/core-rules/v1-0'
import type { CoreRulesDocument } from '@/lib/rules/core-rules-document'

export const CURRENT_PDF_CORE_RULES_VERSION = "1.0"

export const PDF_CORE_RULES_VERSIONS: Record<string, CoreRulesDocument> = {
	"1.0": PDF_CORE_RULES_1_0,
}

export const PDF_CORE_RULES_VERSION_NAMES: Record<string, string> = {
	"1.0": "Launch",
}
`,
				],
			]),
			transcripts: new Map([['CR-v1.0.txt', 'Core transcript\n']]),
			summary: { current: '1.0', transcripts: 1, versions: 1 },
		})
	})

	test('serializes Tournament Rules extraction without source knowledge', () => {
		const registeredVersion = { version: '2026-01-01' }
		const version: ExtractedTournamentRulesFamily['versions'][number] = {
			registeredVersion,
			lastUpdated: registeredVersion.version,
			document: { schemaVersion: 1, version: registeredVersion.version, sections: [] },
			transcript: 'Tournament transcript\n',
			diagnostics: [],
		}

		const prepared = prepareTournamentRulesArtifacts({ versions: [version], currentVersion: version })

		expect(prepared).toStrictEqual({
			artifacts: new Map([
				[
					'v2026-01-01.ts',
					`// Generated by pnpm rules:generate. Do not edit.

import type { TournamentRulesDocument } from '@/lib/rules/tournament-rules-document'

// oxfmt-ignore
export const PDF_TOURNAMENT_RULES_2026_01_01: TournamentRulesDocument = {
  "schemaVersion": 1,
  "version": "2026-01-01",
  "sections": []
}
`,
				],
				[
					'index.ts',
					`// Generated by pnpm rules:generate. Do not edit.

import { PDF_TOURNAMENT_RULES_2026_01_01 } from '@/generated/tournament-rules/v2026-01-01'
import type { TournamentRulesDocument } from '@/lib/rules/tournament-rules-document'

export const CURRENT_PDF_TOURNAMENT_RULES_VERSION = "2026-01-01"

export const PDF_TOURNAMENT_RULES_DOCUMENTS: Record<string, TournamentRulesDocument> = {
	"2026-01-01": PDF_TOURNAMENT_RULES_2026_01_01,
}
`,
				],
			]),
			transcripts: new Map([['Tournament-Rules-2026-01-01.txt', 'Tournament transcript\n']]),
			summary: { current: '2026-01-01', transcripts: 1, versions: 1 },
		})
	})
})
