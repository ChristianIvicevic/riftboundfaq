import type { CoreRulesDocument } from '@/lib/rules/core-rules-document'
import { coreRulesConventions } from '@/lib/rules/document-family-conventions'
import type { ExtractedCoreRulesFamily } from '../rules-document-family'

const GENERATED_HEADER = '// Generated by pnpm rules:generate. Do not edit.\n\n'
export type CoreRulesArtifacts = {
	artifacts: Map<string, string>
	transcripts: Map<string, string>
	summary: { versions: number; transcripts: number; current: string }
}

function serializeVersion(document: CoreRulesDocument, exportName: string) {
	return `${GENERATED_HEADER}import type { CoreRulesDocument } from '@/lib/rules/core-rules-document'\n\n// oxfmt-ignore\nexport const ${exportName}: CoreRulesDocument = ${JSON.stringify(document, null, 2)}\n`
}

function serializeIndex(versions: readonly string[], current: string, versionNames: Record<string, string>) {
	const imports = versions
		.map((version) => {
			const generated = coreRulesConventions.version(version).generated
			return `import { ${generated.exportName} } from '${generated.moduleSpecifier}'`
		})
		.join('\n')
	const entries = versions
		.map(
			(version) =>
				`\t${JSON.stringify(version)}: ${coreRulesConventions.version(version).generated.exportName},`,
		)
		.join('\n')
	const nameEntries = Object.keys(versionNames)
		.map((version) => `\t${JSON.stringify(version)}: ${JSON.stringify(versionNames[version])},`)
		.join('\n')

	const { currentVersionExport, documentsExport, versionNamesExport } = coreRulesConventions.generated
	return `${GENERATED_HEADER}${imports}\nimport type { CoreRulesDocument } from '@/lib/rules/core-rules-document'\n\nexport const ${currentVersionExport} = ${JSON.stringify(current)}\n\nexport const ${documentsExport}: Record<string, CoreRulesDocument> = {\n${entries}\n}\n\nexport const ${versionNamesExport}: Record<string, string> = {\n${nameEntries}\n}\n`
}

export function prepareCoreRulesArtifacts(extracted: ExtractedCoreRulesFamily): CoreRulesArtifacts {
	const versions = extracted.versions.map(({ registeredVersion }) => registeredVersion.version)
	const versionNames = Object.fromEntries(
		extracted.versions.flatMap(({ registeredVersion: { version, name } }) =>
			name === undefined ? [] : [[version, name]],
		),
	)
	const artifacts = new Map<string, string>()
	const transcripts = new Map<string, string>()

	for (const { registeredVersion, document, transcript } of extracted.versions) {
		const { version } = registeredVersion
		const conventions = coreRulesConventions.version(version)
		artifacts.set(
			conventions.generated.filename,
			serializeVersion(document, conventions.generated.exportName),
		)
		if (transcript !== null) transcripts.set(conventions.source.transcriptFilename, transcript)
	}

	const current = extracted.currentVersion.registeredVersion.version
	artifacts.set('index.ts', serializeIndex(versions, current, versionNames))
	return {
		artifacts,
		transcripts,
		summary: {
			versions: versions.length,
			transcripts: transcripts.size,
			current,
		},
	}
}
