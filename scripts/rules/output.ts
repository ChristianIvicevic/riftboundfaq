function getRulesDocumentTemplate(templates: RulesOutputTemplates, filename: TemplateFile): string {
	const template = templates.get(filename)
	if (template === undefined) throw new Error(`${filename}: template was not loaded`)
	return template
}

function validateRulesDocumentTemplates(templates: RulesOutputTemplates): void {
	for (const filename of TEMPLATE_FILES) {
		const template = getRulesDocumentTemplate(templates, filename)
		for (const name of REQUIRED_TEMPLATE_MARKERS[filename]) {
			const marker = `{{${name}}}`
			if (!template.includes(marker)) throw new Error(`${filename}: missing ${marker}`)
		}
		const allowed = new Set<string>(REQUIRED_TEMPLATE_MARKERS[filename])
		const unknown = [...template.matchAll(PLACEHOLDER)].flatMap((match) =>
			allowed.has(match[1]) ? [] : [match[0]],
		)
		if (unknown.length > 0) throw new Error(`${filename}: unresolved placeholders ${unknown.join(', ')}`)
	}
}

function renderTemplate(
	template: string,
	values: Readonly<Record<string, string>>,
	filename: TemplateFile,
): string {
	let rendered = template
	for (const [name, value] of Object.entries(values)) rendered = rendered.replaceAll(`{{${name}}}`, value)
	const unknown = [...rendered.matchAll(PLACEHOLDER)].map((match) => match[0])
	if (unknown.length > 0) throw new Error(`${filename}: unresolved placeholders ${unknown.join(', ')}`)
	return rendered
}

function renderOverviewTiles(tiles: readonly PlannedOverviewTile[]): string {
	return tiles
		.map(
			({ route, title, description }) =>
				`\t<Tile href="${route}" title="${title}">\n\t\t${description}\n\t</Tile>`,
		)
		.join('\n')
}

function metadataPages(pages: readonly string[]): string {
	return pages.map((page) => `\t\t${JSON.stringify(page)}`).join(',\n')
}

function navigationPages(currentCorePath: string, currentTournamentPath: string): string {
	return metadataPages([
		'---Introduction---',
		'index',
		'---Current Documents---',
		currentCorePath,
		currentTournamentPath,
		'---Core Rules---',
		'core-rules/changes',
		'core-rules/(archive)',
		'---Tournament Rules---',
		'tournament-rules/changes',
		'tournament-rules/(archive)',
	])
}

function validateVersionSpecificRulesPages(
	files: readonly DesiredOutputFile[],
	plans: readonly RulesDocumentFamilyPlan[],
): void {
	for (const artifact of plans.flatMap(({ artifacts }) => artifacts)) {
		if (artifact.kind !== 'version-specific-rules-page') continue
		const source = files.find(
			({ path }) => path === `${OUTPUT_ROOTS['rules-documents']}/${artifact.path}`,
		)?.contents
		if (source === undefined) throw new Error(`Missing version-specific rules page artifact ${artifact.path}`)
		const conventions =
			artifact.identity.type === 'core-rules'
				? coreRulesConventions.version(artifact.identity.version)
				: tournamentRulesConventions.version(artifact.identity.version)
		const expectedPath =
			artifact.status === 'current'
				? conventions.reference.currentDocumentPath
				: conventions.reference.archivedDocumentPath
		if (artifact.path !== expectedPath) {
			throw new Error(`Version-specific rules page artifact ${artifact.path} does not match ${expectedPath}`)
		}
		const frontmatter = renderRulesDocumentFrontmatter(artifact.identity)
		const frontmatterEnd = source.startsWith('---\n') ? source.indexOf('\n---', 4) : -1
		const sourceFrontmatter = frontmatterEnd === -1 ? '' : source.slice(4, frontmatterEnd)
		if (
			source.match(/^rulesDocument\s*:/gmu)?.length !== 1 ||
			source.split(frontmatter).length !== 2 ||
			sourceFrontmatter.split(frontmatter).length !== 2
		) {
			throw new Error(
				`Version-specific rules page artifact ${artifact.path} must contain its canonical identity once`,
			)
		}
		if (source.split('<RulesDocument />').length !== 2) {
			throw new Error(
				`Version-specific rules page artifact ${artifact.path} must contain one <RulesDocument />`,
			)
		}
		if (source.includes('<CoreRulesDocument') || source.includes('<TournamentRulesDocument')) {
			throw new Error(
				`Version-specific rules page artifact ${artifact.path} contains a legacy document marker`,
			)
		}
	}
}

function appendRulesDocumentFiles(
	files: DesiredOutputFile[],
	coreRules: ExtractedCoreRulesFamily,
	tournamentRules: ExtractedTournamentRulesFamily,
	templates: RulesOutputTemplates,
): void {
	const corePlan = planCoreRulesDocuments(coreRules)
	const tournamentPlan = planTournamentRulesDocuments(tournamentRules)
	const add = (path: string, contents: string) =>
		files.push(desiredOutputFile('rules-documents', path, contents))
	const render = (filename: TemplateFile, values: Readonly<Record<string, string>>) => {
		try {
			return renderTemplate(getRulesDocumentTemplate(templates, filename), values, filename)
		} catch (cause) {
			throw rulesDocumentPreparationError('render', cause)
		}
	}

	add(
		'index.mdx',
		render('index.mdx', {
			CORE_RULES_ARCHIVE: renderOverviewTiles(corePlan.archiveTiles),
			CORE_RULES_CHANGES: renderOverviewTiles(corePlan.changeTiles),
			CORE_RULES_CURRENT_VERSION_ROUTE: corePlan.currentVersionRoute,
			TOURNAMENT_RULES_ARCHIVE: renderOverviewTiles(tournamentPlan.archiveTiles),
			TOURNAMENT_RULES_CHANGES: renderOverviewTiles(tournamentPlan.changeTiles),
			TOURNAMENT_RULES_CURRENT_VERSION_ROUTE: tournamentPlan.currentVersionRoute,
		}),
	)
	add(
		'meta.json',
		render('meta.json.template', {
			PAGES: navigationPages(corePlan.currentNavigationPath, tournamentPlan.currentNavigationPath),
		}),
	)
	for (const [path, values] of [
		[
			'core-rules/changes/meta.json',
			{ ICON: 'FileDiff', PAGES: metadataPages(corePlan.changeNavigationPages), TITLE: 'Changes' },
		],
		[
			'core-rules/(archive)/meta.json',
			{ ICON: 'Archive', PAGES: metadataPages(corePlan.archiveNavigationPages), TITLE: 'Archive' },
		],
		[
			'tournament-rules/changes/meta.json',
			{ ICON: 'FileDiff', PAGES: metadataPages(tournamentPlan.changeNavigationPages), TITLE: 'Changes' },
		],
		[
			'tournament-rules/(archive)/meta.json',
			{ ICON: 'Archive', PAGES: metadataPages(tournamentPlan.archiveNavigationPages), TITLE: 'Archive' },
		],
	] as const) {
		add(path, render('group-meta.json.template', values))
	}
	for (const artifact of [...corePlan.artifacts, ...tournamentPlan.artifacts]) {
		const values =
			artifact.kind === 'version-specific-rules-page'
				? {
						...artifact.values,
						RULES_DOCUMENT_FRONTMATTER: renderRulesDocumentFrontmatter(artifact.identity),
					}
				: artifact.values
		add(artifact.path, render(artifact.template, values))
	}
	try {
		validateVersionSpecificRulesPages(files, [corePlan, tournamentPlan])
	} catch (cause) {
		throw rulesDocumentPreparationError('artifacts', cause)
	}
}

function expectedOutputPaths(
	coreRules: ExtractedCoreRulesFamily,
	tournamentRules: ExtractedTournamentRulesFamily,
): readonly string[] {
	const coreVersions = coreRules.versions.map(({ registeredVersion }) => registeredVersion.version)
	const tournamentVersions = tournamentRules.versions.map(
		({ registeredVersion }) => registeredVersion.version,
	)
	return [
		desiredOutputFile('core-rules', 'index.ts', '').path,
		...coreRules.versions.flatMap(({ registeredVersion }) => {
			const conventions = coreRulesConventions.version(registeredVersion.version)
			return [
				desiredOutputFile('core-rules', conventions.generated.filename, '').path,
				desiredOutputFile('rules-transcripts', conventions.transcript.filename, '').path,
			]
		}),
		desiredOutputFile('tournament-rules', 'index.ts', '').path,
		...tournamentRules.versions.flatMap(({ registeredVersion }) => {
			const conventions = tournamentRulesConventions.version(registeredVersion.version)
			return [
				desiredOutputFile('tournament-rules', conventions.generated.filename, '').path,
				desiredOutputFile('rules-transcripts', conventions.transcript.filename, '').path,
			]
		}),
		...FIXED_RULES_DOCUMENT_PATHS.map((path) => desiredOutputFile('rules-documents', path, '').path),
		desiredOutputFile(
			'rules-documents',
			coreRulesConventions.version(coreRules.currentVersion.registeredVersion.version).reference
				.currentDocumentPath,
			'',
		).path,
		...coreVersions
			.slice(0, -1)
			.map(
				(version) =>
					desiredOutputFile(
						'rules-documents',
						coreRulesConventions.version(version).reference.archivedDocumentPath,
						'',
					).path,
			),
		...coreVersions
			.slice(1)
			.map(
				(version) =>
					desiredOutputFile('rules-documents', coreRulesConventions.version(version).reference.changePath, '')
						.path,
			),
		desiredOutputFile(
			'rules-documents',
			tournamentRulesConventions.version(tournamentRules.currentVersion.registeredVersion.version).reference
				.currentDocumentPath,
			'',
		).path,
		...tournamentVersions
			.slice(0, -1)
			.map(
				(version) =>
					desiredOutputFile(
						'rules-documents',
						tournamentRulesConventions.version(version).reference.archivedDocumentPath,
						'',
					).path,
			),
		...tournamentVersions
			.slice(1)
			.map(
				(version) =>
					desiredOutputFile(
						'rules-documents',
						tournamentRulesConventions.version(version).reference.changePath,
						'',
					).path,
			),
	]
}

function validateOutputCompleteness(
	files: readonly DesiredOutputFile[],
	expectedPaths: readonly string[],
): void {
	if (files.length !== expectedPaths.length) {
		throw new Error(`Rules generation produced ${files.length} files; expected ${expectedPaths.length}`)
	}
	const actualPathSet = new Set(files.map(({ path }) => path))
	const expectedPathSet = new Set(expectedPaths)
	const missing = expectedPaths.find((path) => !actualPathSet.has(path))
	if (missing !== undefined) throw new Error(`Rules generation did not produce required output ${missing}`)
	const unexpected = files.find(({ path }) => !expectedPathSet.has(path))
	if (unexpected !== undefined)
		throw new Error(`Rules generation produced unexpected output ${unexpected.path}`)
}

function buildDesiredRulesOutput(
	coreRules: ExtractedCoreRulesFamily,
	tournamentRules: ExtractedTournamentRulesFamily,
	templates: RulesOutputTemplates,
): DesiredRulesOutput {
	const files: DesiredOutputFile[] = []
	appendCoreRulesFiles(files, coreRules)
	appendTournamentRulesFiles(files, tournamentRules)
	appendRulesDocumentFiles(files, coreRules, tournamentRules, templates)
	validateOutputCompleteness(files, expectedOutputPaths(coreRules, tournamentRules))
	return {
		files,
		summary: {
			coreRules: {
				current: coreRules.currentVersion.registeredVersion.version,
				versions: coreRules.versions.length,
				transcripts: coreRules.versions.length,
			},
			tournamentRules: {
				current: tournamentRules.currentVersion.registeredVersion.version,
				versions: tournamentRules.versions.length,
				transcripts: tournamentRules.versions.length,
			},
			reference: {
				pages: files.filter(({ owner, path }) => owner === 'rules-documents' && path.endsWith('.mdx')).length,
			},
		},
	}
}

const loadRulesDocumentTemplates = Effect.fnUntraced(function* (templatesDirectory: string) {
	const fileSystem = yield* FileSystem.FileSystem
	const pathService = yield* Path.Path
	const templates = yield* Effect.all(
		TEMPLATE_FILES.map((filename) =>
			fileSystem
				.readFileString(pathService.join(templatesDirectory, filename), 'utf8')
				.pipe(Effect.map((contents) => [filename, contents] as const)),
		),
		{ concurrency: 'unbounded' },
	)
	return new Map(templates)
})

function causeMessage(cause: unknown): string {
	const outward = PlatformError.isPlatformError(cause) ? (cause.reason.cause ?? cause) : cause
	return outward instanceof Error ? outward.message : String(outward)
}

const RULES_DOCUMENT_PREPARATION_OPERATIONS = {
	templates: 'Reference publication templates could not be loaded',
	render: 'Reference publication could not be rendered',
	artifacts: 'Reference publication artifacts are invalid',
} as const
const RULES_DOCUMENT_PREPARATION_ERROR_TAG = 'RulesDocumentPreparationError'

const RulesDocumentPreparationError = Data.TaggedError(RULES_DOCUMENT_PREPARATION_ERROR_TAG)<{
	readonly phase: keyof typeof RULES_DOCUMENT_PREPARATION_OPERATIONS
	readonly message: string
	readonly cause: unknown
}>

function rulesDocumentPreparationError(
	phase: keyof typeof RULES_DOCUMENT_PREPARATION_OPERATIONS,
	cause: unknown,
) {
	return new RulesDocumentPreparationError({
		phase,
		message: `${RULES_DOCUMENT_PREPARATION_OPERATIONS[phase]}: ${causeMessage(cause)}`,
		cause,
	})
}

function isRulesDocumentPreparationError(
	cause: unknown,
): cause is InstanceType<typeof RulesDocumentPreparationError> {
	return cause instanceof RulesDocumentPreparationError
}

function causedOutputError(
	stage: RulesOutputStage,
	message: string,
	cause: unknown,
	context?: RulesOutputContext,
): RulesOutputError {
	return new RulesOutputError({ stage, context, message: `${message}: ${causeMessage(cause)}`, cause })
}

function rulesDocumentOutputError(cause: Error, templatesDirectory: string): RulesOutputError {
	return causedOutputError('rules-documents', 'Rules-document generation failed', cause, {
		kind: 'input',
		path: templatesDirectory,
	})
}

export const loadRulesOutputTemplates = Effect.fn('loadRulesOutputTemplates')(function* (
	templatesDirectory: string,
) {
	const templates = yield* loadRulesDocumentTemplates(templatesDirectory).pipe(
		Effect.mapError((cause) =>
			rulesDocumentOutputError(rulesDocumentPreparationError('templates', cause), templatesDirectory),
		),
	)
	yield* Effect.fromResult(
		Result.try({
			try: () => validateRulesDocumentTemplates(templates),
			catch: (cause) =>
				rulesDocumentOutputError(rulesDocumentPreparationError('render', cause), templatesDirectory),
		}),
	)
	return templates
})

function safeProjectRelativePath(pathService: Path.Path, path: string): boolean {
	return (
		path.length > 0 &&
		!path.includes('\\') &&
		!pathService.isAbsolute(path) &&
		path.split('/').every((segment) => segment.length > 0 && segment !== '.' && segment !== '..')
	)
}

function fileMatchesOwner(file: DesiredOutputFile): boolean {
	return file.path.startsWith(`${OUTPUT_ROOTS[file.owner]}/`)
}

function removalIsOwned(removal: OutputRemoval): boolean {
	if (OWNED_DIRECTORIES.some((path) => path === removal.path)) {
		return removal.recursive
	}
	if (
		RETIRED_OUTPUTS.some(({ path, recursive }) => path === removal.path && recursive === removal.recursive)
	) {
		return true
	}
	return false
}

function outputValidationError(message: string, path?: string): RulesOutputError {
	return new RulesOutputError({
		stage: 'output-validation',
		context: path === undefined ? undefined : { kind: 'output', path },
		message,
		cause: undefined,
	})
}

function resolveOutputPath(
	pathService: Path.Path,
	projectDirectory: string,
	path: string,
): Result.Result<string, RulesOutputError> {
	if (!safeProjectRelativePath(pathService, path)) {
		return Result.fail(outputValidationError(`Unsafe generated output path ${JSON.stringify(path)}`, path))
	}
	const resolved = pathService.resolveWithin(projectDirectory, path)
	if (Option.isNone(resolved)) {
		return Result.fail(outputValidationError(`Generated output path escapes the project: ${path}`, path))
	}
	return Result.succeed(resolved.value)
}

function validateOutputPlan(
	pathService: Path.Path,
	projectDirectory: string,
	files: readonly DesiredOutputFile[],
	removals: readonly OutputRemoval[],
): Result.Result<ValidatedOutputPlan, RulesOutputError> {
	return Result.gen(function* () {
		const resolvedFiles: ValidatedOutputFile[] = []
		for (const file of files) {
			if (!fileMatchesOwner(file)) {
				return yield* Result.fail(
					outputValidationError(`Generated output is not owned by ${file.owner}: ${file.path}`, file.path),
				)
			}
			resolvedFiles.push({
				...file,
				destination: yield* resolveOutputPath(pathService, projectDirectory, file.path),
			})
		}

		const destinations = new Set<string>()
		for (const file of resolvedFiles) {
			if (destinations.has(file.destination)) {
				return yield* Result.fail(
					outputValidationError(`Duplicate generated output destination ${file.path}`, file.path),
				)
			}
			destinations.add(file.destination)
		}
		for (const file of resolvedFiles) {
			const relative = pathService.relative(projectDirectory, file.destination)
			const canonical = pathService.sep === '/' ? relative : relative.replaceAll(pathService.sep, '/')
			if (canonical !== file.path) {
				return yield* Result.fail(
					outputValidationError(`Generated output path is not canonical: ${file.path}`, file.path),
				)
			}
			for (const other of resolvedFiles) {
				if (file === other) continue
				if (other.destination.startsWith(`${file.destination}${pathService.sep}`)) {
					return yield* Result.fail(
						outputValidationError(
							`Generated output path ${file.path} conflicts with descendant ${other.path}`,
							file.path,
						),
					)
				}
			}
		}

		const resolvedRemovals: ValidatedOutputRemoval[] = []
		const removalDestinations = new Set<string>()
		for (const removal of removals) {
			if (!removalIsOwned(removal)) {
				return yield* Result.fail(
					outputValidationError(`Refusing to remove unowned generated path ${removal.path}`, removal.path),
				)
			}
			const destination = yield* resolveOutputPath(pathService, projectDirectory, removal.path)
			if (removalDestinations.has(destination)) {
				return yield* Result.fail(
					outputValidationError(`Duplicate generated removal destination ${removal.path}`, removal.path),
				)
			}
			removalDestinations.add(destination)
			resolvedRemovals.push({ ...removal, destination })
		}

		return {
			files: resolvedFiles.toSorted((left, right) => left.path.localeCompare(right.path, 'en')),
			removals: resolvedRemovals,
		}
	})
}

function planOutputReconciliation(
	pathService: Path.Path,
	projectDirectory: string,
	output: DesiredRulesOutput,
): Result.Result<ValidatedOutputPlan, RulesOutputError> {
	const removals: OutputRemoval[] = [
		...OWNED_DIRECTORIES.map((path) => ({ path, recursive: true })),
		...RETIRED_OUTPUTS,
	]
	return validateOutputPlan(pathService, projectDirectory, output.files, removals)
}

function reconciliationError(operation: string, path: string, cause: unknown): RulesOutputError {
	return causedOutputError(
		'output-reconciliation',
		`Could not ${operation} generated output ${path}`,
		cause,
		{ kind: 'output', path },
	)
}

const reconcileOutput = Effect.fnUntraced(function* (plan: ValidatedOutputPlan) {
	const fileSystem = yield* FileSystem.FileSystem
	const pathService = yield* Path.Path
	for (const removal of plan.removals) {
		yield* fileSystem
			.remove(removal.destination, { recursive: removal.recursive, force: true })
			.pipe(Effect.mapError((cause) => reconciliationError('remove', removal.path, cause)))
	}
	for (const file of plan.files) {
		yield* fileSystem
			.makeDirectory(pathService.dirname(file.destination), { recursive: true })
			.pipe(
				Effect.mapError((cause) => reconciliationError('create the parent directory for', file.path, cause)),
			)
		yield* fileSystem
			.writeFileString(file.destination, file.contents)
			.pipe(Effect.mapError((cause) => reconciliationError('write', file.path, cause)))
	}
})

export const generateRulesOutput = Effect.fn('generateRulesOutput')(function* (
	projectDirectory: string,
	coreRules: ExtractedCoreRulesFamily,
	tournamentRules: ExtractedTournamentRulesFamily,
	templates: RulesOutputTemplates,
) {
	const pathService = yield* Path.Path
	const templatesDirectory = pathService.join(projectDirectory, 'scripts', 'rules', 'templates')
	const output = yield* Effect.fromResult(
		Result.try({
			try: () => buildDesiredRulesOutput(coreRules, tournamentRules, templates),
			catch: (cause) =>
				rulesDocumentOutputError(
					isRulesDocumentPreparationError(cause) ? cause : rulesDocumentPreparationError('artifacts', cause),
					templatesDirectory,
				),
		}),
	)
	const plan = yield* Effect.fromResult(planOutputReconciliation(pathService, projectDirectory, output))
	yield* reconcileOutput(plan)
	return output.summary
})
