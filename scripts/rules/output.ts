function serializeRulesVersion(
	document: CoreRulesDocument | TournamentRulesDocument,
	exportName: string,
	typeName: 'CoreRulesDocument' | 'TournamentRulesDocument',
	typeModule: string,
): string {
	return `${GENERATED_HEADER}import type { ${typeName} } from '${typeModule}'\n\n// oxfmt-ignore\nexport const ${exportName}: ${typeName} = ${JSON.stringify(document, null, 2)}\n`
}

function serializeRulesIndex({
	versions,
	current,
	typeName,
	typeModule,
	currentVersionExport,
	documentsExport,
	versionNames,
}: Readonly<{
	versions: readonly SerializedRulesVersion[]
	current: string
	typeName: 'CoreRulesDocument' | 'TournamentRulesDocument'
	typeModule: string
	currentVersionExport: string
	documentsExport: string
	versionNames?: Readonly<{
		exportName: string
		entries: readonly Readonly<{ version: string; name: string }>[]
	}>
}>): string {
	const imports = versions
		.map(({ exportName, moduleSpecifier }) => `import { ${exportName} } from '${moduleSpecifier}'`)
		.join('\n')
	const documentEntries = versions
		.map(({ version, exportName }) => `\t${JSON.stringify(version)}: ${exportName},`)
		.join('\n')
	const versionNamesSource = versionNames
		? `\n\nexport const ${versionNames.exportName}: Record<string, string> = {\n${versionNames.entries
				.map(({ version, name }) => `\t${JSON.stringify(version)}: ${JSON.stringify(name)},`)
				.join('\n')}\n}`
		: ''
	return `${GENERATED_HEADER}${imports}\nimport type { ${typeName} } from '${typeModule}'\n\nexport const ${currentVersionExport} = ${JSON.stringify(current)}\n\nexport const ${documentsExport}: Record<string, ${typeName}> = {\n${documentEntries}\n}${versionNamesSource}\n`
}

function appendCoreRulesFiles(files: DesiredOutputFile[], family: ExtractedCoreRulesFamily): void {
	const versions: SerializedRulesVersion[] = []
	const versionNames: { version: string; name: string }[] = []
	for (const { registeredVersion, document, transcript } of family.versions) {
		const conventions = coreRulesConventions.version(registeredVersion.version)
		versions.push({ version: registeredVersion.version, ...conventions.generated })
		files.push(
			desiredOutputFile(
				'core-rules',
				conventions.generated.filename,
				serializeRulesVersion(
					document,
					conventions.generated.exportName,
					'CoreRulesDocument',
					'@/lib/rules/core-rules-document',
				),
			),
		)
		if (registeredVersion.name !== undefined) {
			versionNames.push({ version: registeredVersion.version, name: registeredVersion.name })
		}
		files.push(desiredOutputFile('rules-transcripts', conventions.transcript.filename, transcript))
	}
	files.push(
		desiredOutputFile(
			'core-rules',
			'index.ts',
			serializeRulesIndex({
				versions,
				current: family.currentVersion.registeredVersion.version,
				typeName: 'CoreRulesDocument',
				typeModule: '@/lib/rules/core-rules-document',
				currentVersionExport: coreRulesConventions.generated.currentVersionExport,
				documentsExport: coreRulesConventions.generated.documentsExport,
				versionNames: {
					exportName: coreRulesConventions.generated.versionNamesExport!,
					entries: versionNames,
				},
			}),
		),
	)
}

