import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { z } from 'zod'
import type { CardReference } from '@/lib/cards/card-reference'

const cardCatalog = z.array(z.unknown())
const cardCatalogEntry = z.object({
	name: z.string(),
	imageUrl: z.string(),
	abilities: z.string().nullable(),
	effects: z.string().nullable(),
})
const cardErratum = z.object({
	oldText: z.string(),
	newText: z.string(),
})
const cardErrata = z.record(z.string(), z.array(cardErratum).length(1))

function parseImageDimensions(imageUrl: string, cardName: string) {
	const match = /-(\d+)x(\d+)\.[^.]+$/u.exec(new URL(imageUrl).pathname)
	if (!match) throw new TypeError(`Expected card image URL for ${cardName} to contain its dimensions`)

	return { imageWidth: Number(match[1]), imageHeight: Number(match[2]) }
}

function normalizeCardText(text: string | null) {
	return text?.replaceAll(/([+\d-])[ \t]+\[Might\]/gu, '$1[Might]') ?? null
}

export async function generateCardIndex(catalogUrl: URL, errataUrl: URL, outputUrl: URL) {
	const catalog: unknown = JSON.parse(await readFile(catalogUrl, 'utf8'))
	const parsedCatalog = cardCatalog.safeParse(catalog)
	if (!parsedCatalog.success) throw new TypeError('Expected the card catalog to be an array')
	const errata: unknown = JSON.parse(await readFile(errataUrl, 'utf8'))
	const parsedErrata = cardErrata.safeParse(errata)
	if (!parsedErrata.success) throw new TypeError('Expected card errata to contain one correction per card')

	const cardReferences = new Map<string, CardReference>()
	const unmatchedErrataNames = new Set(Object.keys(parsedErrata.data))
	for (const [index, value] of parsedCatalog.data.entries()) {
		const parsedEntry = cardCatalogEntry.safeParse(value)
		if (!parsedEntry.success) {
			throw new TypeError(`Expected card catalog entry ${index} to contain card reference fields`)
		}
		const { name, imageUrl, abilities, effects } = parsedEntry.data
		if (cardReferences.has(name)) throw new Error(`Duplicate card name in catalog: ${name}`)
		const correction = parsedErrata.data[name]?.[0]
		const { imageWidth, imageHeight } = parseImageDimensions(imageUrl, name)

		cardReferences.set(name, {
			imageUrl,
			imageWidth,
			imageHeight,
			currentText: normalizeCardText(correction?.newText ?? abilities),
			effectText: normalizeCardText(effects),
			hasErrata: correction !== undefined,
		})
		unmatchedErrataNames.delete(name)
	}
	if (unmatchedErrataNames.size > 0) {
		throw new Error(`Card errata names are missing from the catalog: ${[...unmatchedErrataNames].join(', ')}`)
	}

	const generatedSource = `// Generated by pnpm cards:generate. Do not edit.

import type { CardReference } from '@/lib/cards/card-reference'

// oxfmt-ignore
export const CARD_REFERENCES: Readonly<Record<string, CardReference>> = Object.freeze(${JSON.stringify(Object.fromEntries(cardReferences), null, 2)})
`

	await mkdir(new URL('.', outputUrl), { recursive: true })
	await writeFile(outputUrl, generatedSource)
	return cardReferences.size
}
